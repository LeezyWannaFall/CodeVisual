import { expect, test } from '@playwright/test'

test('source links survive reload, a new tab, and browser Back/Forward through Request Flow', async ({ page, context }) => {
 const errors: string[] = []
 page.on('pageerror', error => errors.push(error.message))
 await page.goto('http://127.0.0.1:17332/')
 await page.getByLabel('Search packages and symbols').fill('ShowUser')
 await page.locator('.search-result').filter({ hasText: 'ShowUser' }).click()
 await expect(page.getByLabel('Source code')).toContainText('func ShowUser')
 await page.getByLabel('Symbol kind').selectOption('function')
 await page.getByLabel('Exported only').check()
 await page.getByLabel('Filter graph').fill('ShowUser')
 await page.getByRole('button', { name: 'Declaration graph', exact: true }).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(1)
 const sourceURL = page.url()
 expect(new URL(sourceURL).searchParams.get('selectedId')).toBeTruthy()
 await page.reload()
 await expect(page.getByLabel('Source code')).toContainText('func ShowUser')
 await expect(page.getByLabel('Filter graph')).toHaveValue('ShowUser')
 await expect(page.getByLabel('Search packages and symbols')).toHaveValue('ShowUser')
 await expect(page.getByLabel('Symbol kind')).toHaveValue('function')
 await expect(page.getByLabel('Exported only')).toBeChecked()
 await expect(page.getByRole('button', { name: 'Declaration graph', exact: true })).toHaveAttribute('aria-pressed', 'true')
 await expect(page.getByText('Arranging nodes and routing connections…')).toHaveCount(0)
 await page.screenshot({ path: test.info().outputPath('linked-source.png') })
 const linked = await context.newPage()
 await linked.goto(sourceURL)
 await expect(linked.getByLabel('Source code')).toContainText('func ShowUser')
 await expect(linked.getByRole('button', { name: 'Go back', exact: true })).toBeDisabled()
 await linked.close()
 await page.locator('.details').getByRole('button', { name: 'Request flow', exact: true }).click()
 await page.getByLabel('Flow depth').selectOption('2')
 await page.getByLabel('Possible implementations').check()
 await expect(page.getByRole('heading', { name: 'Request flow.' })).toBeVisible()
 await page.goBack()
 await expect(page.getByLabel('Source code')).toContainText('func ShowUser')
 await expect(page.getByLabel('Filter graph')).toHaveValue('ShowUser')
 await expect(page.getByLabel('Symbol kind')).toHaveValue('function')
 await page.reload()
 await page.goForward()
 await expect(page.getByRole('heading', { name: 'Request flow.' })).toBeVisible()
 await expect(page.getByLabel('Flow depth')).toHaveValue('2')
 await expect(page.getByLabel('Possible implementations')).toBeChecked()
 await page.reload()
 await expect(page.getByLabel('Flow depth')).toHaveValue('2')
 await expect(page.getByRole('combobox', { name: 'Flow entry point' })).toContainText('ShowUser')
 await page.setViewportSize({ width: 760, height: 900 })
 await expect(page.getByRole('button', { name: 'Copy view link' })).toBeVisible()
 await expect(page.locator('.details')).toHaveCount(0)
 await expect(page.getByText('Arranging nodes and routing connections…')).toHaveCount(0)
 await page.screenshot({ path: test.info().outputPath('linked-flow-narrow.png') })
 expect(errors).toEqual([])
})

test('package selection, filters, and connection settings survive reload and application Back', async ({ page }) => {
 await page.goto('/')
 await page.getByLabel('External dependencies').check()
 await page.getByLabel('Filter graph').fill('model')
 const model = page.locator('.react-flow__node').filter({ has: page.locator('.node-name', { hasText: /^model$/ }) })
 await model.click()
 await page.getByRole('button', { name: 'Selected node', exact: true }).click()
 await page.getByLabel('Connection direction').selectOption('incoming')
 await page.reload()
 await expect(page.getByLabel('Filter graph')).toHaveValue('model')
 await expect(page.getByLabel('External dependencies')).toBeChecked()
 await expect(page.getByRole('button', { name: 'Selected node', exact: true })).toHaveAttribute('aria-pressed', 'true')
 await expect(page.getByLabel('Connection direction')).toHaveValue('incoming')
 await expect(page.locator('.package-below-map')).toContainText('Reader')
 await page.getByRole('button', { name: /^API/ }).click()
 await page.getByRole('button', { name: 'Go back', exact: true }).click()
 await expect(page.getByLabel('Filter graph')).toHaveValue('model')
 await expect(page.getByLabel('Connection direction')).toHaveValue('incoming')
 await expect(page.locator('.package-below-map')).toContainText('Reader')
 await expect(page.getByRole('button', { name: 'Go back', exact: true })).toBeDisabled()
})

test('empty filters and an out-of-range page explain how to recover', async ({ page }) => {
 await page.goto('http://127.0.0.1:17332/')
 await page.getByRole('button', { name: /^API/ }).click()
 await page.getByLabel('HTTP method').selectOption('DELETE')
 await expect(page.getByRole('heading', { name: 'No matches for these filters' })).toBeVisible()
 await expect(page.getByText('Explorer searches across the whole project.', { exact: false })).toBeVisible()
 await page.getByRole('button', { name: 'Clear view filters' }).click()
 await expect(page.locator('.route-row')).toHaveCount(3)
 await page.goto('/?level=packages&offset=9999')
 await expect(page.getByRole('heading', { name: 'This page is outside the current results' })).toBeVisible()
 await page.getByRole('button', { name: 'First page' }).click()
 await expect(page.locator('.react-flow__node')).not.toHaveCount(0)
 await expect(page.getByRole('heading', { name: 'This page is outside the current results' })).toHaveCount(0)
})

test('stale and missing-object links recover to the project overview', async ({ page }) => {
 await page.goto('/?analysisId=previous-analysis&level=symbols&packageId=missing')
 await expect(page.getByText('This link belongs to a different analysis. Showing the project overview.')).toBeVisible()
 await expect(page.locator('.react-flow__node')).not.toHaveCount(0)
 expect(new URL(page.url()).searchParams.has('packageId')).toBe(false)
 await page.goto('/?level=symbols&packageId=missing')
 await expect(page.getByText('The linked object is unavailable in this analysis. Showing the project overview.')).toBeVisible()
 await expect(page.locator('.react-flow__node')).not.toHaveCount(0)
})

import { expect, test } from '@playwright/test'

test('real URL shortener has routed imports and a clear selected-package view', async ({ page, request }) => {
 test.skip(!process.env.CODEVISUAL_TEST_SHORTENER, 'Set CODEVISUAL_TEST_SHORTENER=1 with the local sibling Go-URL-Shortener checkout.')
 const errors: string[] = []
 page.on('pageerror', e => errors.push(e.message))
 const response = await request.get('http://127.0.0.1:17333/api/v1/graph?level=packages')
 expect(response.ok()).toBe(true)
 const graph = await response.json()
 await page.setViewportSize({ width: 1680, height: 1050 })
 await page.goto('http://127.0.0.1:17333/')
 await page.getByRole('button', { name: 'Collapse inspector', exact: true }).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(graph.nodes.length)
 await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.length)
 await expect(page.getByText('Arranging nodes and routing connections…')).toHaveCount(0)
 await page.screenshot({ path: test.info().outputPath('shortener-overview.png') })
 const handler = graph.nodes.find((n: {label:string}) => n.label === 'handler')
 const incident = graph.edges.filter((e: {sourceId:string;targetId:string}) => e.sourceId === handler.id || e.targetId === handler.id)
 const positions = await page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(n => ({ id:n.getAttribute('data-id'), transform:(n as HTMLElement).style.transform })))
 await page.locator('.react-flow__node').filter({ has: page.locator('.node-name', { hasText: /^handler$/ }) }).click()
 await expect(page.getByRole('button', { name: 'All connections', exact: true })).toHaveAttribute('aria-pressed', 'true')
 await expect(page.getByRole('button', { name: 'Selected node', exact: true })).toHaveAttribute('aria-pressed', 'false')
 await expect(page.locator('.react-flow__node')).toHaveCount(graph.nodes.length)
 await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.length)
 expect(await page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(n => ({ id:n.getAttribute('data-id'), transform:(n as HTMLElement).style.transform })))).toEqual(positions)
 await expect(page.locator('.react-flow__edge.animated')).toHaveCount(incident.length)
 await expect(page.locator('.react-flow__edge:not(.animated)')).toHaveCount(graph.edges.length - incident.length)
 await page.getByRole('button', { name: 'Selected node', exact: true }).click()
 await expect(page.locator('.react-flow__edge')).toHaveCount(incident.length)
 const neighbors = new Set<string>([handler.id])
 for (const edge of incident) { neighbors.add(edge.sourceId); neighbors.add(edge.targetId) }
 await expect(page.locator('.react-flow__node')).toHaveCount(neighbors.size)
 await expect(page.getByText('Arranging nodes and routing connections…')).toHaveCount(0)
 await expect.poll(async () => {
  const bounds = await page.getByLabel('Architecture graph').boundingBox()
  const boxes = await page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(n => { const r = n.getBoundingClientRect(); return { left:r.left, right:r.right, top:r.top, bottom:r.bottom } }))
  return !!bounds && boxes.every(b => b.left >= bounds.x && b.right <= bounds.x + bounds.width && b.top >= bounds.y && b.bottom <= bounds.y + bounds.height)
 }).toBe(true)
 await expect(page.locator('.connection-summary')).toContainText('handler')
 await expect(page.locator('.connection-summary')).toContainText(`${incident.length}/${graph.edges.length} connections shown`)
 await page.screenshot({ path: test.info().outputPath('shortener-handler.png') })
 await page.getByLabel('Connection direction').selectOption('incoming')
 await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.filter((e: {targetId:string}) => e.targetId === handler.id).length)
 await page.getByLabel('Connection direction').selectOption('outgoing')
 await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.filter((e: {sourceId:string}) => e.sourceId === handler.id).length)
 await page.getByRole('button', { name: 'All connections', exact: true }).click()
 await expect(page.locator('.react-flow__edge')).toHaveCount(graph.edges.length)
 await expect(page.locator('.react-flow__node')).toHaveCount(graph.nodes.length)
 await expect(page.locator('.react-flow__minimap')).toHaveCount(0)
 expect(errors).toEqual([])
})

test('long Go source opens a wider panel with wrapping and remains readable on small screens', async ({ page }) => {
 test.skip(!process.env.CODEVISUAL_TEST_SHORTENER, 'Requires the local sibling Go-URL-Shortener checkout.')
 await page.setViewportSize({width:1680,height:1050})
 await page.goto('http://127.0.0.1:17333/')
 const narrow = (await page.locator('.details').boundingBox())!.width
 await page.getByLabel('Search packages and symbols').fill('GetByFullUrl')
 await page.locator('.search-result').filter({hasText:'GetByFullUrl'}).filter({hasText:'PostgresStorage'}).click()
 await expect(page.getByLabel('Source code')).toContainText('func (r *PostgresStorage) GetByFullUrl')
 const wide = (await page.locator('.details-source').boundingBox())!.width
 expect(wide).toBeGreaterThan(narrow + 150)
 await expect(page.getByLabel('Wrap lines')).toBeChecked()
 expect(await page.getByLabel('Source code').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
 const lines = await page.locator('.source-line').count()
 await page.getByLabel('Wrap lines').uncheck()
 await expect(page.getByLabel('Source code')).not.toHaveClass(/wrap-lines/)
 await page.getByLabel('Wrap lines').check()
 await expect(page.locator('.source-line')).toHaveCount(lines)
 await page.screenshot({path:test.info().outputPath('wide-source.png')})
 await page.setViewportSize({width:600,height:900})
 const bounds=(await page.locator('.details-source').boundingBox())!
 expect(bounds.width).toBeLessThanOrEqual(600)
 expect(bounds.x).toBeGreaterThanOrEqual(0)
 expect(await page.getByLabel('Source code').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
 await page.getByRole('button',{name:'Close inspector',exact:true}).click()
 await expect(page.locator('.details-source')).toHaveCount(0)
})

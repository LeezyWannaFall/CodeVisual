import { expect, test } from '@playwright/test'

test('Python-only project exposes modules, classes, source and function flow', async ({ page, request }) => {
 const response = await request.get('http://127.0.0.1:17336/api/v1/project')
 expect((await response.json()).project.languages).toEqual(['python'])
 await page.goto('http://127.0.0.1:17336/')
 await expect(page.locator('.explorer-type')).toHaveText('Python')
 await page.getByLabel('Search packages and symbols').fill('Worker')
 await page.getByRole('button', { name: 'C Worker class', exact: true }).click()
 await expect(page.getByLabel('Source code')).toContainText('class Worker:')
 await expect(page.getByLabel('Source code').locator('.go-keyword').filter({ hasText: /^class$/ })).toHaveCount(1)
 const group = page.locator('.symbol-group').filter({ hasText: 'Worker' })
 await group.locator('summary').click()
 await group.getByRole('button', { name: /run/ }).click()
 await expect(page.getByLabel('Source code')).toContainText('def run')
 await page.getByLabel('Search packages and symbols').fill('handler')
 await page.locator('.search-result').filter({ hasText: 'handler' }).click()
 await page.locator('.details').getByRole('button', { name: 'Request flow', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'Request flow.' })).toBeVisible()
 await expect(page.locator('.react-flow__node').filter({ has: page.locator('.node-name', { hasText: /^fetch_user$/ }) })).toHaveCount(1)
 await page.reload()
 await expect(page.getByRole('heading', { name: 'Request flow.' })).toBeVisible()
 await expect(page.getByRole('combobox', { name: 'Flow entry point' })).toContainText('handler')
})


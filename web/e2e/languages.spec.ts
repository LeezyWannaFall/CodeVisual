test('container source tabs filter nodes and file transfer diagrams expand', async ({ page }) => {
 await page.goto('http://127.0.0.1:17337/')
 await page.getByRole('button', { name: /^Containers/ }).click()
 const tabs = page.getByLabel('Container source')
 await tabs.getByRole('button', { name: 'Dockerfile', exact: true }).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(2)
 await expect(page.locator('.container-title small').first()).toHaveText('BUILD STAGE')
 await page.reload()
 await expect(tabs.getByRole('button', { name: 'Dockerfile', exact: true })).toHaveAttribute('aria-pressed', 'true')
 await expect(page.locator('.react-flow__node')).toHaveCount(2)
 const card = page.locator('.container-file-map').filter({ hasText: 'COPY' }).first()
 const node = card.locator('xpath=..').locator('xpath=..')
 const collapsed = await node.boundingBox()
 const viewportBefore = await page.locator('.react-flow__viewport').getAttribute('style')
 const positionsBefore = await page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(n => (n as HTMLElement).style.transform))
 const edgesBefore = await page.locator('.react-flow__edge-path').evaluateAll(edges => edges.map(e => e.getAttribute('d')))
 await card.locator('summary').click()
 await expect(card.locator('.transfer-route').first()).toBeVisible()
 await expect.poll(async () => (await node.boundingBox())?.height ?? 0).toBeGreaterThan(collapsed!.height)
 await card.locator('summary').click()
 await expect(card.locator('.transfer-route').first()).not.toBeVisible()
 for (let repeat = 0; repeat < 3; repeat++) {
  await card.locator('summary').click()
  await expect(card).toHaveAttribute('open', '')
  await page.waitForTimeout(400)
  expect(await page.locator('.react-flow__viewport').getAttribute('style')).toBe(viewportBefore)
  expect(await page.locator('.react-flow__node').evaluateAll(nodes => nodes.map(n => (n as HTMLElement).style.transform))).toEqual(positionsBefore)
  expect(await page.locator('.react-flow__edge-path').evaluateAll(edges => edges.map(e => e.getAttribute('d')))).toEqual(edgesBefore)
  await expect(page.getByText('Arranging nodes and routing connections…')).toHaveCount(0)
  if (repeat === 0) await page.screenshot({ path: test.info().outputPath('stable-container-expansion.png') })
  await card.locator('summary').click()
  await expect(card).not.toHaveAttribute('open', '')
 }

 await tabs.getByRole('button', { name: 'Docker Compose', exact: true }).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(4)
 await expect(page.locator('.container-title small').filter({ hasText: 'BUILD STAGE' })).toHaveCount(0)
 await tabs.getByRole('button', { name: 'All', exact: true }).click()
 await expect(page.locator('.react-flow__node')).toHaveCount(6)
})

test('inspector collapses without losing selection and the graph gains space', async ({ page }) => {
 await page.goto('/')
 const node = page.locator('.react-flow__node').filter({has:page.locator('.node-name',{hasText:/^model$/})})
 await node.click()
 await expect(page.locator('.details h2')).toHaveText('model')
 const expanded = await page.getByLabel('Architecture graph').boundingBox()
 await page.getByRole('button',{name:'Collapse inspector',exact:true}).click()
 await expect(page.locator('.details')).toHaveCount(0)
 const collapsed = await page.getByLabel('Architecture graph').boundingBox()
 expect(collapsed!.width).toBeGreaterThan(expanded!.width)
 await page.getByRole('button',{name:'Expand inspector',exact:true}).click()
 await expect(page.locator('.details h2')).toHaveText('model')
 await page.getByRole('button',{name:'Close inspector',exact:true}).click()
 await page.reload()
 await expect(page.locator('.details')).toHaveCount(0)
 await page.locator('.react-flow__node').filter({has:page.locator('.node-name',{hasText:/^model$/})}).click()
 await expect(page.locator('.details h2')).toHaveText('model')
})

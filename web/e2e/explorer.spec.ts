import { expect, test } from '@playwright/test'
test('explore a package, declaration, source, and graph filters', async ({ page }) => {
 const errors: string[] = []
 page.on('pageerror', error => errors.push(error.message))
 await page.goto('/')
 await expect(page.getByRole('heading', { name: 'Project architecture.' })).toBeVisible()
 const node = page.locator('.react-flow__node').filter({ has: page.locator('.node-name', { hasText: /^model$/ }) })
 await expect(node).toBeVisible()
 for (const selector of ['.app-header', '.workspace-tabs', '.explorer', '.graph-main', '.details', '.app-footer']) {
  const color = await page.locator(selector).evaluate(el => getComputedStyle(el).backgroundColor)
  const channels = color.match(/\d+/g)!.slice(0,3).map(Number)
  expect(channels[0]).toBe(channels[1])
  expect(channels[1]).toBe(channels[2])
  expect(Math.max(...channels)).toBeLessThanOrEqual(18)
 }
 const controls = await page.locator('.react-flow__controls').boundingBox()
 const legend = await page.locator('.canvas-legend').boundingBox()
 expect(controls!.y + controls!.height).toBeLessThanOrEqual(legend!.y)
 await page.locator('.react-flow__controls-fitview').click()
 await expect(page.locator('.react-flow__minimap')).toHaveCount(0)
 const beforeDrag = await node.evaluate(el => (el as HTMLElement).style.transform)
 const card = await node.boundingBox()
 await page.mouse.move(card!.x + card!.width / 2, card!.y + card!.height / 2)
 await page.mouse.down()
 await page.mouse.move(card!.x + card!.width / 2 + 45, card!.y + card!.height / 2 + 25, { steps: 8 })
 await page.mouse.up()
 expect(await node.evaluate(el => (el as HTMLElement).style.transform)).toBe(beforeDrag)
 await node.click()
 const animatedPath = page.locator('.react-flow__edge.animated .react-flow__edge-path').first()
 await expect(animatedPath).toBeAttached()
 expect(await animatedPath.evaluate(el => getComputedStyle(el).visibility)).toBe('visible')
 expect(await animatedPath.evaluate(el => getComputedStyle(el).strokeDasharray)).not.toBe('none')
 expect(await animatedPath.evaluate(el => getComputedStyle(el).animationName)).toBe('dashdraw')
 const offset = await animatedPath.evaluate(el => getComputedStyle(el).strokeDashoffset)
 await expect.poll(() => animatedPath.evaluate(el => getComputedStyle(el).strokeDashoffset)).not.toBe(offset)
 await page.screenshot({ path: test.info().outputPath("overview.png") })
 await node.dblclick()
 await expect(page.getByRole('heading', { name: 'model.' })).toBeVisible()
 await page.getByLabel('Symbol kind').selectOption('interface')
 const reader = page.locator('.react-flow__node').filter({ hasText: 'Reader' })
 await reader.click()
 await expect(page.getByLabel('Source code')).toContainText('type Reader interface')
 await expect(page.locator('.source-line.highlighted')).toHaveCount(3)
 await page.getByLabel('Exported only').check()
 await page.getByRole('button', { name: 'Directories', exact: true }).click()
 await expect(page.locator('.node-name', { hasText: /^model$/ })).toBeVisible()
 await page.getByRole('button', { name: 'Packages', exact: true }).click()
 await page.getByLabel('External dependencies').check()
 await expect(page.locator('.node-name', { hasText: /^fmt$/ })).toBeVisible()
 await page.getByLabel('Filter graph').fill('nothing-matches')
 await expect(page.getByText('No nodes in this view')).toBeVisible()
 expect(errors).toEqual([])
})

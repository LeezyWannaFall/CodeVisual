import { expect, test } from '@playwright/test'
test('booking service package presents types with collapsed methods instead of a symbol web', async ({ page }) => {
 test.skip(!process.env.CODEVISUAL_TEST_BOOKING, 'Requires sibling Room-Booking-Service checkout')
 await page.goto('http://127.0.0.1:17334/')
 await page.getByRole('button', { name: 'Close inspector', exact: true }).click()
 await page.locator('.react-flow__node').filter({ has: page.locator('.node-name', { hasText: /^service$/ }) }).dblclick()
 await expect(page.locator('.symbol-overview')).toBeVisible()
 const booking = page.locator('.symbol-group').filter({ has: page.locator('.symbol-group-title strong', { hasText: /^BookingService$/ }) })
 await expect(booking).toBeVisible()
 await expect(page.locator('.react-flow__node')).toHaveCount(0)
 await expect(booking.locator('.symbol-methods').first()).not.toHaveAttribute('open', '')
 await expect.poll(() => booking.evaluate(el => getComputedStyle(el).opacity)).toBe('1')

 const boxes = await page.locator('.symbol-group').evaluateAll(nodes => nodes.map(node => { const r = node.getBoundingClientRect(); return { top: Math.round(r.top), bottom: Math.round(r.bottom), width: Math.round(r.width) } }))
 for (const box of boxes) {
  const row = boxes.filter(other => other.top === box.top)
  expect(new Set(row.map(other => other.bottom)).size).toBe(1)
  expect(Math.max(...row.map(other => other.width)) - Math.min(...row.map(other => other.width))).toBeLessThanOrEqual(1)
 }
 await page.screenshot({ path: test.info().outputPath('booking-overview.png') })
 await booking.locator('summary').filter({ hasText: 'Methods' }).click()
 await booking.getByRole('button', { name: /CreateBooking/ }).click()
 await expect(page.locator('.details h2')).toHaveText('CreateBooking')
 await expect(page.getByLabel('Source code')).toContainText('CreateBooking')
 await page.locator('.details').getByRole('button', { name: 'Request flow', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'Request flow.' })).toBeVisible()
 await page.getByRole('button', { name: 'Go back', exact: true }).click()
 await expect(page.locator('.symbol-overview')).toBeVisible()
 await expect(page.locator('.details h2')).toHaveText('CreateBooking')
 await page.getByRole('button', { name: 'Go back', exact: true }).click()
 await expect(page.getByRole('heading', { name: 'Project architecture.' })).toBeVisible()
})

